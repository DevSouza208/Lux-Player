-- [LUX-BACKEND-018] Fontes M3U secundárias e revisão de possíveis duplicados.
-- A M3U principal continua fora destas tabelas e mantém prioridade absoluta.
create table if not exists public.secondary_content_sources (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 1 and 80),
  source_url text not null check (source_url ~* '^https?://'),
  source_type text not null default 'auto' check (source_type in ('auto','anime','series','movies','live')),
  priority integer not null default 10 check (priority between 1 and 999),
  enabled boolean not null default true,
  fill_only boolean not null default true,
  review_duplicates boolean not null default true,
  last_checked_at timestamptz,
  last_status text,
  last_error text,
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists secondary_content_sources_enabled_priority_idx
  on public.secondary_content_sources (enabled, priority, created_at);

create table if not exists public.secondary_content_reviews (
  id bigint generated by default as identity primary key,
  source_id uuid not null references public.secondary_content_sources(id) on delete cascade,
  fingerprint text not null,
  incoming_title text not null default '',
  incoming_type text not null default '',
  candidate_key text not null default '',
  candidate_title text not null default '',
  score integer not null default 0 check (score between 0 and 100),
  status text not null default 'pending' check (status in ('pending','merged','separate','ignored')),
  incoming_meta jsonb not null default '{}'::jsonb,
  candidate_meta jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by text,
  unique (source_id, fingerprint)
);

create index if not exists secondary_content_reviews_status_idx
  on public.secondary_content_reviews (status, created_at desc);

-- Estas tabelas nunca são acessadas diretamente pelo navegador.
-- A Edge Function usa service_role e autenticação revogável lux_auth_resolve.
alter table public.secondary_content_sources enable row level security;
alter table public.secondary_content_reviews enable row level security;
revoke all on table public.secondary_content_sources from anon, authenticated;
revoke all on table public.secondary_content_reviews from anon, authenticated;
grant all on table public.secondary_content_sources to service_role;
grant all on table public.secondary_content_reviews to service_role;
grant usage, select on sequence public.secondary_content_reviews_id_seq to service_role;
